/// One level: its number (1-200), its area name, and its governorate.
class LevelDef {
  const LevelDef({
    required this.number,
    required this.area,
    required this.governorate,
    required this.sectionIndex,
  });
  final int number;
  final String area;
  final String governorate;
  final int sectionIndex;

  /// Target score: rises with the level number.
  int get targetScore => 1000 + (number - 1) * 100;

  /// Moves allowed: fewer as the sections get harder.
  int get moves => 30 - sectionIndex;

  /// How many sweet types are on the board (5 early, 6 later).
  int get numTypes => number <= 15 ? 5 : 6;

  /// Blockers (chocolate) on the board; none in Baghdad, more later.
  int get blockerCount => switch (sectionIndex) {
        0 => 0,
        1 => 4,
        2 => 6,
        3 => 8,
        4 => 10,
        5 => 12,
        _ => 14,
      };

  /// Star thresholds: 1 star at target, 2 at 1.6x, 3 at 2.3x.
  int get twoStarScore => (targetScore * 1.6).round();
  int get threeStarScore => (targetScore * 2.3).round();

  int starsForScore(int score) {
    if (score >= threeStarScore) return 3;
    if (score >= twoStarScore) return 2;
    if (score >= targetScore) return 1;
    return 0;
  }
}

